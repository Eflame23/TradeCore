-- 3. Create persistent orders table
CREATE TABLE IF NOT EXISTS orders (
    id VARCHAR(100) PRIMARY KEY,
    symbol VARCHAR(50) DEFAULT 'BTC-USD' NOT NULL,
    user_id VARCHAR(50) NOT NULL,
    side VARCHAR(10) NOT NULL,
    order_type VARCHAR(10) DEFAULT 'LIMIT' NOT NULL,
    price NUMERIC(18,4),
    qty BIGINT NOT NULL,
    filled_qty BIGINT DEFAULT 0 NOT NULL,
    status VARCHAR(20) DEFAULT 'OPEN' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_orders_user_id ON orders(user_id);
CREATE INDEX IF NOT EXISTS idx_orders_symbol ON orders(symbol);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders(status);

-- 4. Create trade audit log table
CREATE TABLE IF NOT EXISTS trade_audits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_id VARCHAR(100) NOT NULL,
    buy_order_id VARCHAR(100) NOT NULL,
    sell_order_id VARCHAR(100) NOT NULL,
    buyer_id VARCHAR(50) NOT NULL,
    seller_id VARCHAR(50) NOT NULL,
    price NUMERIC(18,4) NOT NULL,
    qty BIGINT NOT NULL,
    match_reason TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_trade_audits_trade_id ON trade_audits(trade_id);
CREATE INDEX IF NOT EXISTS idx_trade_audits_buyer_id ON trade_audits(buyer_id);
CREATE INDEX IF NOT EXISTS idx_trade_audits_seller_id ON trade_audits(seller_id);

